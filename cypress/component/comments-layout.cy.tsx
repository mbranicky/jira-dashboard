import {mount} from 'cypress/react';
import {Harness,stubRpc,site} from '../support/harness';
for(const width of [1440,390])it(`compact nested comments and header actions at ${width}px`,()=>{
 cy.viewport(width,900);stubRpc();
 const comments=[0,1,2].map(i=>({id:String(i+1),parentId:i?String(i):null,author:`Author ${i+1}`,created:'2026-11-01T10:00:00Z',updated:i?'2026-11-02T10:00:00Z':null,blocks:[{kind:'paragraph',runs:[{text:`Comment body ${i+1}`}]}],restricted:false}));
 cy.intercept('POST','/__rpc/comments.list',{site,comments,nextStart:null,total:3});
 mount(<Harness transport="twg"/>);cy.get('[aria-label^="Open details for TEST-1:"]').click();
 cy.get('[aria-label="Comment by Author 1"]').scrollIntoView().within(()=>{
  cy.get('[aria-label="Open comment in Jira"]').focus();cy.contains('Open comment in Jira').should('be.visible');
  cy.get('[aria-label="Open comment in Jira"]').then($button=>{cy.contains('Author 1').then($author=>expect(Math.abs($button[0].getBoundingClientRect().top-($author![0] as HTMLElement).getBoundingClientRect().top)).lessThan(12));});
  cy.contains('Reply').should('not.exist');
 });
 cy.get('[aria-label="Comment by Author 3"]').scrollIntoView().should('be.visible').then($row=>expect($row[0].getBoundingClientRect().width).greaterThan(width===390?250:400));
 cy.screenshot(`nested-comments-${width}`);
});

